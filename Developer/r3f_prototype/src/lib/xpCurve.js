// 레벨업 XP 곡선 정본(single source).
//
// 이 값을 다른 파일에 복사하지 말 것. 과거에 useGameStore와 stageBalanceProbe가
// 각자 `xpToNext = 4` / `Math.ceil(xpToNext * 1.24 + 2)` 리터럴을 들고 있어서,
// 한쪽만 고치면 측정 프로브가 옛 곡선으로 돌면서 "고쳐졌다"는 거짓 합격을 냈다.
// 실게임(useGameStore)과 측정 하네스(stageBalanceProbe)는 반드시 여기서 읽는다.
//
// ── 2026-08-08 초반 XP 스노볼 제거 ──────────────────────────────────────────
// 이전: start 4, growth 1.24 → 4,7,11,16,22,30,40,52
// 첫 관문 4가 최약체 E01 한 마리 XP(당시 6)보다 낮아서 "1마리 처치 = 레벨2"였다.
// 스테이지2는 오프닝에 E01을 대량으로 쏟아붓기 때문에 첫 레벨업 중앙값이 3.55초까지
// 내려갔고(스테이지1은 33.75초), 이후 전 구간이 오버파워로 흘렀다.
//
// 지금: start 9, growth 1.12 → 9,13,17,22,27,33,39,46,54,63,73,84
// start 9 = E01(xp 4) 3마리분. 첫 레벨업이 잡몹 여러 마리를 요구한다.
// growth를 1.24 → 1.12로 낮춘 것은 초반 관문을 올린 만큼 중후반 레벨업 페이스를
// 되돌려주기 위해서다. start만 올리면 곡선 전체가 비례해 늘어나 240초 최종 레벨이
// 스테이지1 기준 -31.7%까지 빠졌다(목표는 "초반 폭발 제거"이지 "전체 둔화"가 아니다).
//
// 실측(stageBalanceProbe, 시드 12개, 동일 XP 타임라인에 곡선만 대입한 통제 비교):
//   첫 레벨업 중앙값  스2 3.55초 → 31.55초 / 스1 33.75초 → 38.15초 / 격차 9.51배 → 1.21배
//   240초 최종 레벨(평균)  스1 8.17→6.50  스2 9.17→7.92  스3 8.08→7.00  스4 7.08→5.58
// 곡선 계수는 전 스테이지 공용이므로 스테이지3·4까지 함께 재고 바꿨다.
export const XP_TO_NEXT_START = 9

export const XP_CURVE_GROWTH = 1.12
export const XP_CURVE_FLAT = 2

export function nextXpThreshold(current) {
  return Math.ceil(current * XP_CURVE_GROWTH + XP_CURVE_FLAT)
}
